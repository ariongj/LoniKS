#!/usr/bin/env python3
"""Write js/image-sizes.js: the width and height of every photo in assets/img.

The site uses these to give each <img> its width and height, so the browser
reserves the right space before the photo arrives. Run it again after adding
or replacing photos:

    python3 tools/image-sizes.py

Needs Pillow (pip install pillow).
"""
from pathlib import Path

from PIL import Image

root = Path(__file__).resolve().parent.parent
sizes = {}
for f in sorted((root / "assets" / "img").glob("*.webp")):
    if f.stem.endswith("-960"):
        continue  # the small copies share the shape of the full-size photo
    with Image.open(f) as im:
        sizes[f"assets/img/{f.name}"] = [im.width, im.height]

out = root / "js" / "image-sizes.js"
out.write_text(
    "/* Generated by tools/image-sizes.py: width and height of each photo. Do not edit by hand. */\n"
    "window.IMG_SIZES = {\n"
    + ",\n".join(f'  "{k}": [{w}, {h}]' for k, (w, h) in sizes.items())
    + "\n};\n",
    encoding="utf-8",
)
print(f"{len(sizes)} photos -> {out.relative_to(root)}")
